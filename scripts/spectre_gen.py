#!/usr/bin/env python3
"""Spectre port of scripts/adc_gen.py: translate the transistor-level SAR ADC netlist
(spice/cells.sp + spice/adc_130b.sp) to Spectre syntax on the Cadence gpdk180 models.

Device mapping (GF180MCU ngspice -> gpdk180 Spectre):
  nmos_3p3 / pmos_3p3   -> nmos1 / pmos1   (BSIM3v3, 1.8 V core devices, L = 0.18 um minimum)
  mim_2p0fF             -> mimcap          (cj = 1 fF/um2, cjsw = 0.1 fF/um; 25 fF unit cell = 4.804 um square)
Supply: gpdk180 is a 1.8 V process, so VDD = VREF = 1.8 V and VCM = 0.9 V (full scale 1.8 V, LSB 112.5 mV).
All widths are unchanged from the GF180 netlist.  Results are gpdk180 results, NOT GF180.

  spectre_gen.py --out DIR --name NAME [--corner NN|FF|SS|FS|SF|stat] [--vdd 1.8] [--temp 27]
                 [--mc SEED] [--vin dc:V | ramp:N | rampr:N:LO:HI | sine:CYCLES:SAMPLES]
                 [--mim] [--noise MV_RMS] [--noise_seed 1] [--tstop NS]
Writes DIR/NAME.scs (plus DIR/NAME_*.pwl stimulus files).  The PDK model directory is taken from
$GPDK180_MODELS (the folder holding gpdk.scs).
"""
import argparse, math, os, pathlib, re
import numpy as np

T = 120  # ns per conversion (6 clocks of 20 ns)
ROOT = pathlib.Path(__file__).resolve().parent.parent
DL = "0.5u"          # source/drain diffusion length used for as/ad/ps/pd
UNIT_W_MIM = 4.804e-6  # um-square MIM unit cell = 25.0 fF with cj=1 fF/um2, cjsw=0.1 fF/um


def val(x):
    return x.strip("{}")


def conv_x(line):
    tok = line.split()
    idx = [i for i, t in enumerate(tok) if "=" in t]
    m = idx[0] - 1 if idx else len(tok) - 1
    name, nodes, model, params = tok[0], tok[1:m], tok[m], tok[m + 1:]
    nl = " ".join(nodes)
    if model in ("nmos_3p3", "pmos_3p3"):
        p = {k.lower(): val(v) for k, v in (q.split("=", 1) for q in params)}
        w = p["w"]
        dev = "nmos1" if model.startswith("n") else "pmos1"
        return (f"{name} ({nl}) {dev} w={w} l=ll as=({w})*dl ad=({w})*dl "
                f"ps=2*(({w})+dl) pd=2*(({w})+dl)")
    return f"{name} ({nl}) {model}" + "".join(f" {q.replace('{', '').replace('}', '')}" for q in params)


def translate(text, mim):
    subckts, top = [], []
    cur = None
    for raw in text.splitlines():
        s = raw.strip()
        if not s:
            continue
        if s.startswith("*"):
            (cur if cur is not None else top).append("// " + s.lstrip("* "))
            continue
        low = s.lower()
        if low.startswith(".subckt"):
            t = s.split()
            cur = [f"subckt {t[1]} ({' '.join(t[2:])})"]
        elif low.startswith(".ends"):
            cur.append("ends"); subckts.append("\n".join(cur)); cur = None
        elif low.startswith((".include", ".param", ".options", ".control", ".endc", ".end", "tran", "wrdata")):
            continue
        elif s[0] in "Vv":
            continue            # sources are generated by this script
        elif s[0] in "Xx":
            (cur if cur is not None else top).append(conv_x(s))
        elif s[0] in "Cc":
            t = s.split()
            name, n1, n2, v = t[0], t[1], t[2], val(t[3])
            if mim and name in ("C0", "C1", "C2", "C3", "CT"):
                k = int(eval(v.replace("cu", "1"))) if name != "CT" else 1
                a, pr = UNIT_W_MIM ** 2, 4 * UNIT_W_MIM
                top.extend(f"CM{name}_{i} ({n1} {n2}) mimcap area={a:.6g} perim={pr:.6g}" for i in range(k))
            else:
                top.append(f"{name} ({n1} {n2}) capacitor c={v}")
        else:
            raise SystemExit(f"cannot translate: {s}")
    return subckts, top


def pwl_points(kind, a, vdd):
    pts = []
    if kind == "ramp":
        n = int(a[0]); lo, hi = 0.0, 1.0
    else:
        n, lo, hi = int(a[0]), float(a[1]), float(a[2])
    cur = lo * vdd
    pts.append((0.0, cur))
    for k in range(n):
        v = (lo + (k + 0.5) * (hi - lo) / n) * vdd
        t0 = T * k + 2
        pts.append((t0 * 1e-9, cur)); pts.append(((t0 + 0.5) * 1e-9, v)); cur = v
    return n, pts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True); ap.add_argument("--name", required=True)
    ap.add_argument("--corner", default="NN"); ap.add_argument("--vdd", type=float, default=1.8)
    ap.add_argument("--temp", type=float, default=27.0)
    ap.add_argument("--mc", type=int, default=0, help="0 = off; N>0 = one Monte Carlo (mismatch) iteration with seed N")
    ap.add_argument("--vin", default="dc:0.9"); ap.add_argument("--mim", action="store_true")
    ap.add_argument("--noise", type=float, default=0.0); ap.add_argument("--noise_seed", type=int, default=1)
    ap.add_argument("--tstop", type=float, default=0.0)
    a = ap.parse_args()
    models = os.environ["GPDK180_MODELS"]
    out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    vdd = a.vdd

    cells = (ROOT / "spice/cells.sp").read_text()
    adc = (ROOT / "spice/adc_130b.sp").read_text()
    sub1, top1 = translate(cells, a.mim)
    sub2, top2 = translate(adc, a.mim)

    kind, *arg = a.vin.split(":")
    n_conv = 2
    src = []
    if kind == "dc":
        src.append(f"VIN (vin_s 0) vsource dc={float(arg[0])}")
    elif kind in ("ramp", "rampr"):
        n_conv, pts = pwl_points(kind, arg, vdd)
        f = out / f"{a.name}_vin.pwl"; f.write_text("\n".join(f"{t:.10g} {v:.6f}" for t, v in pts) + "\n")
        src.append(f'VIN (vin_s 0) vsource type=pwl file="{f.name}"')
    elif kind == "sine":
        cyc, ns = int(arg[0]), int(arg[1]); n_conv = ns
        freq = cyc / (ns * T * 1e-9)
        src.append(f"VIN (vin_s 0) vsource type=sine sinedc={vdd/2} ampl={0.49*vdd} freq={freq:.6g}")
    else:
        raise SystemExit("bad --vin")
    tstop = a.tstop or (T * n_conv + 20)
    if a.noise and kind != "dc":
        # series white Gaussian noise source, new value every 0.937 ns (a 1 ns step collides with clock edges)
        rng = np.random.default_rng(a.noise_seed)
        step = 0.937e-9; nsamp = int(tstop * 1e-9 / step) + 2
        samp = rng.normal(0.0, a.noise * 1e-3, nsamp); edge = 20e-12
        lines = []
        for i, v in enumerate(samp):
            lines.append(f"{i * step:.10g} {v:.6g}"); lines.append(f"{(i + 1) * step - edge:.10g} {v:.6g}")
        nf = out / f"{a.name}_noise.pwl"; nf.write_text("\n".join(lines) + "\n")
        src.append(f'VN (vin_n vin_s) vsource type=pwl file="{nf.name}"')
        src.append("RSN (vin_n vin) resistor r=10")
    else:
        src.append("RSN (vin_s vin) resistor r=0.001")

    sec = "stat" if a.mc else a.corner
    net = [f"// generated by scripts/spectre_gen.py  corner={sec} vdd={vdd} temp={a.temp} mc_seed={a.mc} vin={a.vin} "
           f"mim={a.mim} noise_mV={a.noise}",
           "// gpdk180 results -- NOT GF180MCU",
           "simulator lang=spectre", "global 0",
           f'include "{models}/gpdk.scs" section={sec}',
           f"parameters wn=2u wp=2u ll=0.18u dl={DL} cu=25f",
           f"VDD (vdd 0) vsource dc={vdd}", f"VREF (vref 0) vsource dc={vdd}", f"VCM (vcm 0) vsource dc={vdd/2}",
           f"VCK (clk 0) vsource type=pulse val0=0 val1={vdd} delay=10n rise=100p fall=100p width=9.9n period=20n",
           f"VRST (rst 0) vsource type=pwl wave=[0 {vdd} 25n {vdd} 25.1n 0]"]
    net += sub1 + sub2 + top2 + src
    # note: top-level lines of cells.sp (none) are ignored
    sigs = "clk vin top comp q0 q1 q2 setb3 setb2 setb1 setb0 eoc r3 r2 r1 r0 dac3 dac2 dac1 dac0 outp outn s0 pht"
    net.append(f"simulatorOptions options temp={a.temp} tnom=27")
    tran = f"tran tran stop={tstop}n errpreset=conservative maxstep=100p"
    if a.mc:
        net.append(f"mc montecarlo seed={a.mc} numruns=1 variations=mismatch donominal=no savefamilyplots=no {{\n  {tran}\n}}")
    else:
        net.append(tran)
    net.append(f"save {sigs}")
    (out / f"{a.name}.scs").write_text("\n".join(net) + "\n")


if __name__ == "__main__":
    main()
