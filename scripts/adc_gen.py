#!/usr/bin/env python3
"""Generate a variant of the complete 4-bit SAR ADC netlist (spice/adc_130b.sp) with a chosen
process corner, supply, temperature, mismatch seed and input stimulus.

  adc_gen.py --models DIR --out run.sp --data run.txt [--corner typical|ff|ss|fs|sf]
             [--vdd 2.0] [--temp 27] [--mismatch SEED] [--vin dc:1.3 | ramp:N | rampr:N:LO:HI | sine:CYCLES:SAMPLES]

Vref = VDD and Vcm = VDD/2, so full scale follows the supply.  One conversion takes 120 ns
(6 clocks of 20 ns); the first end-of-conversion is at about 130 ns.
"""
import argparse, math, re, pathlib

T = 120  # ns per conversion
ap = argparse.ArgumentParser()
ap.add_argument("--models", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--data", required=True)
ap.add_argument("--corner", default="typical")
ap.add_argument("--vdd", type=float, default=2.0)
ap.add_argument("--temp", type=float, default=27.0)
ap.add_argument("--mismatch", type=int, default=0, help="0 = off, N>0 = mismatch on with seed N")
ap.add_argument("--vin", default="dc:1.3")
ap.add_argument("--mim", action="store_true", help="use the PDK MIM-cap model (mim_2p0fF) instead of ideal capacitors")
ap.add_argument("--noise", type=float, default=0.0, help="white Gaussian input noise, mV rms (series source, 0.937 ns step)")
ap.add_argument("--noise_seed", type=int, default=1)
ap.add_argument("--tstop", type=float, default=0.0, help="ns; default derived from the stimulus")
a = ap.parse_args()

src = (pathlib.Path(__file__).resolve().parent.parent / "spice" / "adc_130b.sp").read_text()
vdd = a.vdd

n_conv = 2
kind = a.vin.split(":")[0]
if kind == "dc":
    vin = f"VIN vin 0 {float(a.vin.split(':')[1])}"
elif kind == "ramp":
    n = int(a.vin.split(":")[1]); n_conv = n
    pts = ["0 0"]
    for k in range(n):
        v = (k + 0.5) * vdd / n
        t0 = T * k + 2
        pts.append(f"{t0}n {pts[-1].split()[1]}")
        pts.append(f"{t0 + 0.5}n {v:.6f}")
    vin = "VIN vin 0 pwl(" + " ".join(pts) + ")"
elif kind == "rampr":      # rampr:N:lo:hi -- N mid-step inputs between lo and hi (in units of VDD)
    _, n, lo, hi = a.vin.split(":"); n = int(n); lo, hi = float(lo), float(hi); n_conv = n
    pts = ["0 " + f"{lo * vdd:.6f}"]
    for k in range(n):
        v = (lo + (k + 0.5) * (hi - lo) / n) * vdd
        t0 = T * k + 2
        pts.append(f"{t0}n {pts[-1].split()[1]}")
        pts.append(f"{t0 + 0.5}n {v:.6f}")
    vin = "VIN vin 0 pwl(" + " ".join(pts) + ")"
elif kind == "sine":
    _, cyc, ns = a.vin.split(":"); cyc, ns = int(cyc), int(ns); n_conv = ns
    f = cyc / (ns * T * 1e-9)
    vin = f"VIN vin 0 sin({vdd/2} {0.49*vdd} {f:.6g})"
else:
    raise SystemExit("bad --vin")
tstop = a.tstop or (T * n_conv + 20)

hdr = f"""* generated by scripts/adc_gen.py: corner={a.corner} vdd={vdd} temp={a.temp} mismatch_seed={a.mismatch} vin={a.vin}
.include {a.models}/design.ngspice
.lib {a.models}/sm141064.ngspice {a.corner}
.param sw_stat_global=0 sw_stat_mismatch={1 if a.mismatch else 0}
.temp {a.temp}
""" + (f".option seed={a.mismatch}\n" if a.mismatch else "")
if a.mim:
    mimlib = {"ss": "mimcap_ss", "ff": "mimcap_ff"}.get(a.corner, "mimcap_typical")
    hdr += f".lib {a.models}/sm141064.ngspice {mimlib}\n"
if a.noise:
    hdr += f".option seed={a.noise_seed}\n" if not a.mismatch else ""
src = src.replace(".include models.sp\n", hdr)
src = src.replace("VDD vdd 0 2\n", f"VDD vdd 0 {vdd}\n")
src = src.replace("VREF vref 0 2\n", f"VREF vref 0 {vdd}\n")
src = src.replace("VCM vcm 0 1\n", f"VCM vcm 0 {vdd/2}\n")
src = src.replace("VCK clk 0 pulse(0 2 10n", f"VCK clk 0 pulse(0 {vdd} 10n")
src = src.replace("VRST rst 0 pwl(0 2 25n 2 25.1n 0)", f"VRST rst 0 pwl(0 {vdd} 25n {vdd} 25.1n 0)")
src = re.sub(r"^VIN vin 0 .*$", vin, src, flags=re.M)
if a.mim:
    W = "3.31u"   # unit cell: 1.99 fF/um2 * W^2 + 0.238 fF/um * 4W = 25.0 fF at 27 C
    def cap(m):
        name, node, n = m.group(1), m.group(2), int(m.group(3))
        return "\n".join(f"XM{name}_{i} top {node} mim_2p0fF c_length={W} c_width={W}" for i in range(n))
    src = re.sub(r"^C(\d) top (b\d) \{(\d)\*cu\}$", cap, src, flags=re.M)
    src = re.sub(r"^CT top (bt) \{cu\}$", lambda m: cap(re.match(r"(T) top (bt) \{(1)\*cu\}", "T top bt {1*cu}")), src, flags=re.M)
if a.mim:
    # the PDK MIM model makes ngspice 36 abort at t ~ 0.2 ps ("timestep too small"); these solver options avoid it
    src = src.replace(".options method=gear", ".options method=gear gmin=1e-10 cshunt=1e-18 itl4=100")
if a.noise:
    src = src.replace(vin.split()[0] + " vin 0 ", "VIN vin_s 0 ", 1)
    src = src.replace("VIN vin_s 0 ", f"VN vin_n vin_s trnoise({a.noise * 1e-3:g} 0.937n 0 0 0 0 0)\nRSN vin_n vin 10\nVIN vin_s 0 ", 1)
src = re.sub(r"tran 20p [0-9.]+n", f"tran 20p {tstop}n", src)
src = re.sub(r"wrdata \S+", f"wrdata {a.data}", src)
pathlib.Path(a.out).write_text(src)
